create or replace function public.community_contains_blocked_word(input_text text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.community_blocked_words w
    where w.active
      and (
        lower(w.term) = any(
          regexp_split_to_array(lower(coalesce(input_text, '')), '[^[:alnum:]_]+')
        )
        or (
          w.term ~ '[^\x00-\x7F]'
          and position(lower(w.term) in lower(coalesce(input_text, ''))) > 0
        )
      )
  );
$$;

revoke all on function public.community_contains_blocked_word(text) from public;
grant execute on function public.community_contains_blocked_word(text)
  to anon, authenticated;

create table if not exists public.community_post_images (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.community_posts(id) on delete cascade,
  position smallint not null check (position between 0 and 5),
  image_path text,
  image_url text,
  created_at timestamptz not null default now(),
  unique(post_id, position),
  check (num_nonnulls(image_path, image_url) = 1)
);

alter table public.community_post_images enable row level security;

drop policy if exists community_post_images_read on public.community_post_images;
create policy community_post_images_read on public.community_post_images
for select using (
  exists (
    select 1 from public.community_posts p
    where p.id = post_id and p.moderation_status = 'approved'
  )
);

drop policy if exists community_post_images_owner on public.community_post_images;
create policy community_post_images_owner on public.community_post_images
for all using (
  exists (
    select 1 from public.community_posts p
    where p.id = post_id and p.author_id = auth.uid() and not p.is_seed
  )
) with check (
  exists (
    select 1 from public.community_posts p
    where p.id = post_id and p.author_id = auth.uid() and not p.is_seed
  )
);

insert into public.community_post_images(post_id, position, image_path, image_url)
select id, 0, image_path, image_url
from public.community_posts
where num_nonnulls(image_path, image_url) = 1
on conflict (post_id, position) do update set
  image_path = excluded.image_path,
  image_url = excluded.image_url;

